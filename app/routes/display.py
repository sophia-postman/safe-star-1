"""
Blueprint for the Display route.

Routes:
  GET /display  - Get message display upon completed safety checks
                  Accepts JSON body with 'driver' and 'vehicle' fields (IDs).
"""

from flask import Blueprint, request, jsonify

from app.auth import require_auth
from app import store

display_bp = Blueprint("display", __name__)


def _build_message(driver_profile: dict, vehicle_profile: dict) -> tuple[str, str]:
    """Build a personalised safety message and HTML snippet."""
    first_name = driver_profile.get("driver", {}).get("firstName", "Driver")
    last_name = driver_profile.get("driver", {}).get("lastName", "")
    safety_score = driver_profile.get("safetyScore", 100)
    active_codes = vehicle_profile.get("activeCodes", [])
    risk_score = vehicle_profile.get("riskScore", 0)
    make = vehicle_profile.get("make", "your vehicle")
    model = vehicle_profile.get("model", "")

    # Safety score tier
    if safety_score >= 90:
        score_msg = "Excellent driving behaviour — keep it up!"
        score_color = "#2ecc71"
    elif safety_score >= 70:
        score_msg = "Good driving behaviour with room for improvement."
        score_color = "#f39c12"
    else:
        score_msg = "Your driving behaviour needs attention. Please review your recent trips."
        score_color = "#e74c3c"

    # OBD code advisory
    if active_codes:
        codes_str = ", ".join(active_codes)
        code_advisory = (
            f"⚠️ Active OBD-II codes detected on your {make} {model}: <strong>{codes_str}</strong>. "
            "Please schedule a service appointment as soon as possible."
        )
    else:
        code_advisory = f"✅ No active OBD-II fault codes detected on your {make} {model}."

    plain_message = (
        f"Hello {first_name} {last_name}! "
        f"Your safety score is {safety_score}/100. {score_msg} "
        f"Vehicle risk score: {risk_score}/100. {code_advisory.replace('<strong>', '').replace('</strong>', '')}"
    )

    html = f"""
<div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #ddd; border-radius: 8px;">
  <h2 style="color: #2c3e50;">SafeStar Safety Report</h2>
  <p>Hello, <strong>{first_name} {last_name}</strong>!</p>
  <h3 style="color: {score_color};">Driver Safety Score: {safety_score} / 100</h3>
  <p>{score_msg}</p>
  <h3>Vehicle Risk Score: {risk_score} / 100</h3>
  <p>{code_advisory}</p>
  <hr/>
  <p style="font-size: 12px; color: #999;">Generated by SafeStar Service &mdash; Drive safe.</p>
</div>
""".strip()

    return plain_message, html


@display_bp.route("/display", methods=["GET"])
@require_auth
def get_display():
    body = request.get_json(silent=True) or {}
    driver_id_raw = body.get("driver")
    vehicle_id_raw = body.get("vehicle")

    if driver_id_raw is None or vehicle_id_raw is None:
        return (
            jsonify(
                {
                    "error": {
                        "code": "VALIDATION_ERROR",
                        "message": "Both 'driver' and 'vehicle' fields are required in the request body.",
                        "details": {"fields": ["driver", "vehicle"]},
                    }
                }
            ),
            400,
        )

    try:
        driver_id = int(driver_id_raw)
        vehicle_id = int(vehicle_id_raw)
    except (ValueError, TypeError):
        return (
            jsonify(
                {
                    "error": {
                        "code": "VALIDATION_ERROR",
                        "message": "'driver' and 'vehicle' must be integer IDs.",
                        "details": {"fields": ["driver", "vehicle"]},
                    }
                }
            ),
            400,
        )

    driver_profile = store.driver_profiles.get(driver_id)
    if driver_profile is None:
        return (
            jsonify(
                {
                    "error": {
                        "code": "PROFILE_NOT_FOUND",
                        "message": f"Driver safety profile for driver {driver_id} was not found.",
                        "details": {"driverId": driver_id},
                    }
                }
            ),
            404,
        )

    vehicle_profile = store.vehicle_profiles.get(vehicle_id)
    if vehicle_profile is None:
        return (
            jsonify(
                {
                    "error": {
                        "code": "PROFILE_NOT_FOUND",
                        "message": f"Vehicle safety profile for vehicle {vehicle_id} was not found.",
                        "details": {"vehicleId": vehicle_id},
                    }
                }
            ),
            404,
        )

    message, html = _build_message(driver_profile, vehicle_profile)
    return (
        jsonify(
            {
                "message": message,
                "html": html,
                "driverId": driver_id,
                "vehicleId": vehicle_id,
                "safetyScore": driver_profile.get("safetyScore", 100),
                "riskScore": vehicle_profile.get("riskScore", 0),
            }
        ),
        200,
    )
